package li.com.bobsonclinic.data;

;

public class BOBActivity {
	private String id;
	private String time;
	private String title;
	private String entry;
	private String member_limit;
	private String fee;
	private String img;
	private String css_path;
	private String lesson_id;
	private String member_count;
	private String join_status;

	public String getId() {
		return id;
	}

	public void setId(String id) {
		this.id = id;
	}

	public String getTime() {
		return time;
	}

	public void setTime(String time) {
		this.time = time;
	}

	public String getTitle() {
		return title;
	}

	public void setTitle(String title) {
		this.title = title;
	}

	public String getEntry() {
		return entry;
	}

	public void setEntry(String entry) {
		this.entry = entry;
	}

	public String getMember_limit() {
		return member_limit;
	}

	public void setMember_limit(String member_limit) {
		this.member_limit = member_limit;
	}

	public String getFee() {
		return fee;
	}

	public void setFee(String fee) {
		this.fee = fee;
	}

	public String getImg() {
		return img;
	}

	public void setImg(String img) {
		this.img = img;
	}

	public String getCss_path() {
		return css_path;
	}

	public void setCss_path(String css_path) {
		this.css_path = css_path;
	}

	public String getLesson_id() {
		return lesson_id;
	}

	public void setLesson_id(String lesson_id) {
		this.lesson_id = lesson_id;
	}

	public String getMember_count() {
		return member_count;
	}

	public void setMember_count(String member_count) {
		this.member_count = member_count;
	}

	public String getJoin_status() {
		return join_status;
	}

	public void setJoin_status(String join_status) {
		this.join_status = join_status;
	}
}
