package li.com.bobsonclinic.data;

;

public class BOBBabySwim {
	private String status;
	private String message;
	private String stop_at;
	private String rtsp_uri;


	public String getStatus() {
		return status;
	}

	public void setStatus(String status) {
		this.status = status;
	}

	public String getMessage() {
		return message;
	}

	public void setMessage(String message) {
		this.message = message;
	}

	public String getStop_at() {
		return stop_at;
	}

	public void setStop_at(String stop_at) {
		this.stop_at = stop_at;
	}

	public String getRtsp_uri() {
		return rtsp_uri;
	}

	public void setRtsp_uri(String rtsp_uri) {
		this.rtsp_uri = rtsp_uri;
	}
}
